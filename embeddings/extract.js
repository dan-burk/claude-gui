'use strict';

// Session → embeddable text chunks. Pure functions apart from the transcript
// readers at the bottom, so the chunking and cleaning are unit-testable.
//
// Only spoken text is embedded: user prompts and assistant prose. Tool calls,
// tool results and summaries are skipped, and harness-injected blocks are
// stripped from user text so a chunk reflects what a person actually said.

const fs = require('fs');
const readline = require('readline');

const MAX_CHUNK = 1800;
const OVERLAP = 150;
const MIN_CHUNK = 15;
const PREVIEW_LEN = 200;

// Harness blocks injected into user turns (Claude Code, Codex, Antigravity).
// Each is removed with its contents.
const NOISE_TAGS = [
  'system-reminder', 'command-name', 'command-message', 'command-args', 'command-contents',
  'local-command-stdout', 'local-command-stderr', 'local-command-caveat',
  'bash-input', 'bash-stdout', 'bash-stderr', 'task-notification',
  'user-prompt-submit-hook', 'autonomous-loop', 'autonomous-loop-dynamic',
  'ide_selection', 'ide_opened_file', 'ide_diagnostics',
  'environment_context', 'user_instructions', 'permissions instructions',
  'collaboration_mode', 'apps_instructions', 'plugins_instructions',
  'skills_instructions', 'INSTRUCTIONS', 'turn_aborted', 'user_shell_command',
];
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const NOISE_RE = new RegExp(`<(${NOISE_TAGS.map(escapeRe).join('|')})(\\s[^>]*)?>[\\s\\S]*?</\\1>`, 'g');
// An opening tag whose block was cut off (no closing tag): drop to the end.
const NOISE_OPEN_RE = new RegExp(`<(${NOISE_TAGS.map(escapeRe).join('|')})(\\s[^>]*)?>[\\s\\S]*$`);
const NOISE_LINES = [
  /^\[Request interrupted by user[^\]]*\]$/gm,
  /^Caveat: The messages below were generated by the user while running local commands\..*$/gm,
  /^# AGENTS\.md instructions for .*$/gm,
];

function cleanText(text, role) {
  let out = String(text || '');
  if (role === 'user') {
    out = out.replace(NOISE_RE, ' ').replace(NOISE_OPEN_RE, ' ');
    for (const re of NOISE_LINES) out = out.replace(re, ' ');
  }
  return out
    .replace(/\r\n?/g, '\n')
    .replace(/[ \t\f\v]+/g, ' ')
    .replace(/ *\n */g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

// Split on the last good boundary at or before `max`: paragraph, then line,
// then sentence end, then word; hard cut as a last resort.
function cutPoint(text, max) {
  const window = text.slice(0, max);
  const floor = Math.floor(max * 0.4);  // don't make tiny head pieces
  for (const re of [/\n\n/g, /\n/g, /[.!?](\s)/g, /\s/g]) {
    let best = -1, m;
    re.lastIndex = 0;
    while ((m = re.exec(window))) best = m.index + m[0].length;
    if (best >= floor) return best;
  }
  return max;
}

// Long text → pieces of ≤ max chars, each starting a little before the
// previous one ended (on a word boundary) so context isn't lost at cuts.
function chunkText(text, max = MAX_CHUNK, overlap = OVERLAP) {
  const out = [];
  let rest = String(text || '').trim();
  while (rest.length > max) {
    const cut = cutPoint(rest, max);
    out.push(rest.slice(0, cut).trim());
    let next = Math.max(cut - overlap, 1);
    const sp = rest.indexOf(' ', next);
    if (sp > 0 && sp < cut) next = sp + 1;
    rest = rest.slice(next).trim();
  }
  if (rest) out.push(rest);
  return out.filter(Boolean);
}

// Standard message list → logical turns. Consecutive messages from one role
// merge (Claude writes each assistant content block on its own line, and tool
// results arrive as user-role messages with no text) so a turn is everything
// one side said before the other side spoke.
function turnsFromMessages(messages) {
  const turns = [];
  for (const m of messages || []) {
    if (!m || m.type !== 'turn') continue;
    if (m.role !== 'user' && m.role !== 'assistant') continue;
    const text = (m.parts || [])
      .filter(p => p && p.kind === 'text' && p.text)
      .map(p => cleanText(p.text, m.role))
      .filter(Boolean)
      .join('\n\n');
    if (!text) continue;
    const last = turns[turns.length - 1];
    if (last && last.role === m.role) last.text += '\n\n' + text;
    else turns.push({ role: m.role, timestamp: m.timestamp || '', text });
  }
  return turns;
}

function preview(text) {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > PREVIEW_LEN ? flat.slice(0, PREVIEW_LEN - 1) + '…' : flat;
}

// Messages → [{role, timestamp, text, preview}], ready to embed.
function chunksFromMessages(messages, opts = {}) {
  const max = opts.max || MAX_CHUNK;
  const overlap = opts.overlap ?? OVERLAP;
  const chunks = [];
  for (const turn of turnsFromMessages(messages)) {
    for (const piece of chunkText(turn.text, max, overlap)) {
      if (piece.replace(/\s+/g, '').length < MIN_CHUNK) continue;
      chunks.push({ role: turn.role, timestamp: turn.timestamp, text: piece, preview: preview(piece) });
    }
  }
  return chunks;
}

// ── Transcript readers ────────────────────────────────────────────────
// Claude Code JSONL, text parts only. Lighter than the viewer's parser (no
// tool rendering) and skips isMeta lines, which are harness-injected.
function readClaudeMessages(filePath) {
  return new Promise((resolve) => {
    const messages = [];
    const rl = readline.createInterface({ input: fs.createReadStream(filePath), crlfDelay: Infinity });
    rl.on('line', (line) => {
      if (!line.trim()) return;
      let d; try { d = JSON.parse(line); } catch { return; }
      if ((d.type !== 'user' && d.type !== 'assistant') || d.isMeta || !d.message) return;
      const c = d.message.content;
      const parts = typeof c === 'string'
        ? [{ kind: 'text', text: c }]
        : (Array.isArray(c) ? c : []).filter(p => p && p.type === 'text' && p.text).map(p => ({ kind: 'text', text: p.text }));
      // Keep tool-only messages as empty turns so role boundaries stay right.
      messages.push({ type: 'turn', role: d.type, timestamp: d.timestamp || '', parts });
    });
    rl.on('close', () => resolve(messages));
    rl.on('error', () => resolve(messages));
  });
}

// Dispatch to the provider's message parser. `session` is the job entry the
// server hands the worker: {provider, filePath?, rawConversation?}.
async function messagesForSession(session) {
  switch (session.provider) {
    case 'claude': return readClaudeMessages(session.filePath);
    case 'codex': return require('../codex-sessions').parseCodexMessages(session.filePath);
    case 'antigravity': return require('../antigravity-sessions').parseAntigravityMessages(session.filePath);
    case 'chatgpt': return require('../chatgpt-sessions').parseChatGptMessages(session.rawConversation);
    case 'claude-export': return require('../claude-export-sessions').parseClaudeExportMessages(session.rawConversation);
    default: return [];
  }
}

module.exports = {
  MAX_CHUNK, OVERLAP, MIN_CHUNK, PREVIEW_LEN,
  cleanText, chunkText, turnsFromMessages, chunksFromMessages, preview,
  readClaudeMessages, messagesForSession,
};
